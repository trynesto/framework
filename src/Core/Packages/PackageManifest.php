<?php

declare(strict_types=1);

namespace Nesto\Core\Packages;

/**
 * The Nesto packages installed in a project, discovered from Composer (like Laravel's package discovery).
 *
 * A package opts in from its composer.json:
 *
 *   "extra": {
 *       "nesto": {
 *           "module": "Acme\\Mail\\MailModule",                      // or a list; imported by `php nesto add`
 *           "commands": ["Acme\\Mail\\Commands\\MailTestCommand"],    // registered in `php nesto` automatically
 *           "config": { "mail": "config/mail.php" }                 // default config under the "mail" key
 *       }
 *   }
 *
 * The manifest is cached next to vendor/composer/installed.json and rebuilt whenever Composer changes it.
 */
final class PackageManifest
{
    private const CACHE_FILE = 'nesto-packages.php';

    /** @var array<string, self> per vendor dir, for the lifetime of the process */
    private static array $loaded = [];

    /**
     * @param array<string, array{name: string, path: string, modules: list<string>, commands: list<string>, config: array<string, string>}> $packages
     */
    private function __construct(public readonly array $packages) {}

    /** The manifest of the running project (located through Composer's autoloader), cached on disk. */
    public static function forProject(?string $vendorDir = null): self
    {
        $vendorDir ??= self::vendorDir();
        if ($vendorDir === null) {
            return new self([]);
        }
        $vendorDir = rtrim($vendorDir, '/');
        if (isset(self::$loaded[$vendorDir])) {
            return self::$loaded[$vendorDir];
        }

        $installed = "$vendorDir/composer/installed.json";
        $cache = "$vendorDir/" . self::CACHE_FILE;
        if (is_file($cache) && (! is_file($installed) || filemtime($cache) >= filemtime($installed))) {
            $packages = require $cache;
            if (is_array($packages)) {
                return self::$loaded[$vendorDir] = new self($packages);
            }
        }

        $manifest = self::build($vendorDir);
        $manifest->write($cache);

        return self::$loaded[$vendorDir] = $manifest;
    }

    /** Read vendor/composer/installed.json and keep the packages that declare `extra.nesto`. */
    public static function build(string $vendorDir): self
    {
        $vendorDir = rtrim($vendorDir, '/');
        $file = "$vendorDir/composer/installed.json";
        $data = is_file($file) ? json_decode((string) file_get_contents($file), true) : null;
        $list = is_array($data) ? ($data['packages'] ?? $data) : []; // Composer 2 wraps the list, Composer 1 does not

        $packages = [];
        foreach ($list as $package) {
            $extra = $package['extra']['nesto'] ?? null;
            if (! is_array($extra) || ! isset($package['name'])) {
                continue;
            }
            $name = (string) $package['name'];
            $path = isset($package['install-path'])
                ? self::normalize("$vendorDir/composer/" . $package['install-path'])
                : "$vendorDir/$name";

            $config = [];
            foreach ((array) ($extra['config'] ?? []) as $key => $relative) {
                $config[(string) $key] = $path . '/' . ltrim((string) $relative, '/');
            }

            $packages[$name] = [
                'name' => $name,
                'path' => $path,
                'modules' => array_values(array_map('strval', (array) ($extra['module'] ?? $extra['modules'] ?? []))),
                'commands' => array_values(array_map('strval', (array) ($extra['commands'] ?? []))),
                'config' => $config,
            ];
        }
        ksort($packages);

        return new self($packages);
    }

    /** Write the cache file; a read-only vendor dir just means the manifest is rebuilt on every boot. */
    public function write(string $file): void
    {
        $code = "<?php\n\n// Generated by Nesto package discovery. Do not edit.\n\nreturn " . var_export($this->packages, true) . ";\n";
        $tmp = $file . '.' . getmypid() . '.tmp';
        if (@file_put_contents($tmp, $code) !== false) {
            @rename($tmp, $file);
        }
    }

    /** Forget cached manifests (tests, `php nesto add` after composer require). */
    public static function flush(): void
    {
        self::$loaded = [];
    }

    /** @return array{name: string, path: string, modules: list<string>, commands: list<string>, config: array<string, string>}|null */
    public function find(string $package): ?array
    {
        return $this->packages[strtolower($package)] ?? $this->packages[$package] ?? null;
    }

    /** @return list<class-string> */
    public function commands(): array
    {
        return array_merge(...array_values(array_map(fn (array $p) => $p['commands'], $this->packages)), ...[[]]);
    }

    /** @return array<string, string> config key => absolute path of the package's default config file */
    public function configFiles(): array
    {
        $files = [];
        foreach ($this->packages as $package) {
            $files += $package['config'];
        }

        return $files;
    }

    /** The project's vendor dir, from the location of Composer's ClassLoader. */
    public static function vendorDir(): ?string
    {
        if (! class_exists(\Composer\Autoload\ClassLoader::class)) {
            return null;
        }
        $file = (new \ReflectionClass(\Composer\Autoload\ClassLoader::class))->getFileName();

        return $file === false ? null : dirname($file, 2);
    }

    private static function normalize(string $path): string
    {
        return realpath($path) ?: $path;
    }
}
