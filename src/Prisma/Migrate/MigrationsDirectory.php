<?php

declare(strict_types=1);

namespace Nesto\Prisma\Migrate;

use Nesto\Prisma\PrismaException;

/**
 * prisma/migrations: one folder per migration ("20241013093000_init/migration.sql"), applied in name order,
 * and migration_lock.toml recording the provider the history was written for.
 */
final class MigrationsDirectory
{
    public const LOCK_FILE = 'migration_lock.toml';

    public function __construct(public readonly string $path) {}

    /** @return list<LocalMigration> */
    public function migrations(): array
    {
        if (! is_dir($this->path)) {
            return [];
        }
        $migrations = [];
        foreach (scandir($this->path) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..' || ! is_dir($this->path . '/' . $entry)) {
                continue;
            }
            if (is_file($this->path . '/' . $entry . '/migration.sql')) {
                $migrations[] = new LocalMigration($entry, $this->path . '/' . $entry);
            }
        }
        usort($migrations, fn (LocalMigration $a, LocalMigration $b) => strcmp($a->name, $b->name));

        return $migrations;
    }

    public function find(string $name): ?LocalMigration
    {
        foreach ($this->migrations() as $migration) {
            if ($migration->name === $name) {
                return $migration;
            }
        }

        return null;
    }

    /** Create "<UTC timestamp>_<name>/migration.sql" (and the lock file). */
    public function create(string $name, string $sql, string $provider, ?\DateTimeInterface $now = null): LocalMigration
    {
        $slug = trim((string) preg_replace('/[^A-Za-z0-9_]+/', '_', str_replace([' ', '-'], '_', $name)), '_');
        $timestamp = ($now ?? new \DateTimeImmutable('now', new \DateTimeZone('UTC')))->format('YmdHis');
        // never reuse / precede an existing folder (two migrations in the same second)
        foreach ($this->migrations() as $existing) {
            $existingStamp = substr($existing->name, 0, 14);
            if (ctype_digit($existingStamp) && strcmp($existingStamp, $timestamp) >= 0) {
                $timestamp = (string) ((int) $existingStamp + 1);
            }
        }
        $folder = $timestamp . ($slug !== '' ? '_' . substr($slug, 0, 200) : '');
        $dir = $this->path . '/' . $folder;
        if (! is_dir($dir) && ! mkdir($dir, 0777, true) && ! is_dir($dir)) {
            throw new PrismaException("Could not create the migration folder $dir.");
        }
        file_put_contents($dir . '/migration.sql', $sql);
        $this->writeLock($provider);

        return new LocalMigration($folder, $dir);
    }

    /** The provider recorded in migration_lock.toml (null without one). */
    public function lockedProvider(): ?string
    {
        $file = $this->path . '/' . self::LOCK_FILE;
        if (! is_file($file)) {
            return null;
        }
        if (preg_match('/^\s*provider\s*=\s*"([^"]+)"/m', (string) file_get_contents($file), $m) === 1) {
            return $m[1];
        }

        return null;
    }

    public function writeLock(string $provider): void
    {
        if (! is_dir($this->path)) {
            mkdir($this->path, 0777, true);
        }
        file_put_contents(
            $this->path . '/' . self::LOCK_FILE,
            "# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = \"$provider\"\n",
        );
    }

    /** Prisma's P3019 when the history was written for another provider. */
    public function assertProvider(string $provider): void
    {
        $locked = $this->lockedProvider();
        if ($locked !== null && $locked !== $provider && ! ($locked === 'mysql' && $provider === 'mariadb') && ! ($locked === 'mariadb' && $provider === 'mysql')) {
            throw new PrismaException(sprintf(
                "The datasource provider `%s` specified in your schema does not match the one specified in the migration_lock.toml, `%s`. Please remove your current migration directory and start a new migration history with prisma migrate dev. Read more: https://pris.ly/d/migrate-provider-switch",
                $provider,
                $locked,
            ));
        }
    }
}
