<?php

declare(strict_types=1);

namespace Nesto\Orm\Migration;

use Nesto\Orm\Schema\Comparison\Comparator;
use Nesto\Orm\Schema\Comparison\SchemaDiff;
use Nesto\Orm\Schema\Introspection\Introspector;
use Nesto\Orm\Schema\Table;
use Nesto\Orm\Schema\View;

/**
 * TypeORM's `migration:generate`: compares wanted tables (schema model — for entities, from
 * Mapping\EntitySchemaBuilder) with the live database and writes a migration whose up() applies the
 * difference and whose down() reverts it, as Schema / Blueprint calls.
 *
 *   $tables = (new EntitySchemaBuilder)->tables([User::class, Post::class]);
 *   $generator = new MigrationGenerator($dataSource->schema());
 *   [$up, $down] = $generator->diffs($tables);
 *   $code = $generator->generate($tables, 'AddNickname20260101120000');   // null: no changes
 */
final class MigrationGenerator
{
    public function __construct(private readonly Schema $schema) {}

    /**
     * @param array<string, Table> $wanted tables in creation order
     * @param array<string, View>  $wantedViews
     * @return array{0: SchemaDiff, 1: SchemaDiff} [up, down]
     */
    public function diffs(array $wanted, array $wantedViews = []): array
    {
        $introspector = Introspector::for($this->schema->getConnection());
        $current = $introspector->tables(array_keys($wanted));
        $comparator = new Comparator($this->schema->grammar());
        $up = $comparator->compare($current, $wanted);
        $down = $comparator->compare($wanted, $current, array_map(fn ($table) => $table->name, $up->created));
        if ($wantedViews !== []) {
            $currentViews = $introspector->views($this->schema->metadataTable(), array_keys($wantedViews));
            $touched = SchemaSynchronizer::touchedTables($up);
            $comparator->compareViews($up, $currentViews, $wantedViews, [], $touched);
            $comparator->compareViews($down, $wantedViews, $currentViews, array_keys(array_diff_key($wantedViews, $currentViews)), $touched);
        }

        return [$up, $down];
    }

    /**
     * @param array<string, Table> $wanted
     * @param array<string, View>  $wantedViews
     * @return ?string the migration class source, null when nothing changed
     */
    public function generate(array $wanted, string $class, ?string $comment = null, array $wantedViews = []): ?string
    {
        [$up, $down] = $this->diffs($wanted, $wantedViews);
        if ($up->isEmpty()) {
            return null;
        }
        $platform = $this->schema->getConnection()->platform();

        return (new MigrationRenderer)->renderClass(
            $class,
            $up,
            $down,
            $comment ?? sprintf('Generated by `migration:generate` (against %s) on %s.', $platform, date('Y-m-d H:i:s')),
        );
    }
}
