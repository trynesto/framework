<?php

declare(strict_types=1);

namespace Nesto\Orm\Migration;

use Nesto\Orm\Connection;
use Nesto\Orm\Schema\Column;
use Nesto\Orm\Schema\Check;
use Nesto\Orm\Schema\ForeignKey;
use Nesto\Orm\Schema\Index;
use Nesto\Orm\OrmException;
use Nesto\Orm\SqlExpression;
use Nesto\Orm\Types\TypeRegistry;

/**
 * Compiles Blueprints into DDL for SQLite, MySQL, MariaDB and PostgreSQL.
 *
 * Type map (Blueprint / #[Column] type → SQL):
 *
 *   type                 sqlite    mysql / mariadb                 pgsql
 *   int / integer        INTEGER   INTEGER                         INTEGER (SERIAL when auto-increment)
 *   smallint / tinyint   INTEGER   SMALLINT / TINYINT              SMALLINT
 *   bigint               INTEGER   BIGINT                          BIGINT (BIGSERIAL when auto-increment)
 *   float / double       REAL      DOUBLE                          DOUBLE PRECISION
 *   real                 REAL      DOUBLE                          REAL
 *   decimal / numeric    DECIMAL   DECIMAL                         DECIMAL (NUMERIC)
 *   bool / boolean       INTEGER   TINYINT(1)                      BOOLEAN
 *   string / varchar     VARCHAR   VARCHAR                         VARCHAR
 *   char                 CHAR      CHAR                            CHAR
 *   text (medium/long)   TEXT      TEXT / MEDIUMTEXT / LONGTEXT    TEXT
 *   json / jsonb         TEXT      JSON (MariaDB: LONGTEXT alias)  JSONB (json: JSONB, jsonb: JSONB)
 *   date / time          DATE/TIME DATE/TIME                       DATE/TIME
 *   datetime / timestamp DATETIME  DATETIME                        TIMESTAMP
 *   timestamptz          DATETIME  TIMESTAMP                       TIMESTAMPTZ
 *   uuid                 CHAR(36)  CHAR(36)                        UUID
 *   enum / simple-enum   VARCHAR + CHECK (col IN (...))  ENUM(...)  the enumName type (VARCHAR(255) without one)
 *   simple-array / -json TEXT      TEXT                            TEXT
 *   blob / binary        BLOB      BLOB / BINARY(n)                BYTEA
 *
 * Registered custom types (Types\TypeRegistry) declare their own SQL. Any other type name is written
 * upper-cased (`inet`, `point`, ...). PostgreSQL also has array columns (`INTEGER[]`), identity columns
 * (GENERATED BY DEFAULT AS IDENTITY) and gen_random_uuid() defaults for generated uuids; generated columns
 * (GENERATED ALWAYS AS (...) STORED / VIRTUAL) work on every database (PostgreSQL < 18: STORED only).
 */
final class Grammar
{
    public function __construct(private readonly Connection $connection) {}

    public function connection(): Connection
    {
        return $this->connection;
    }

    /** @return list<string> */
    public function compileCreate(Blueprint $blueprint, bool $ifNotExists = false): array
    {
        $q = fn (string $s) => $this->connection->quote($s);
        $driver = $this->connection->driver();
        $this->assertSupported($blueprint->columns, $blueprint->primaryKeys);
        $statements = $this->enumTypeStatements($blueprint->columns);
        $definitions = [];
        $primary = $blueprint->primaryKeys;
        $namedPrimary = $blueprint->primaryKeyName !== null && $driver === 'pgsql';
        if ($namedPrimary && $primary === []) {
            foreach ($blueprint->columns as $column) {
                if ($column->primary) {
                    $primary[] = $column->name;
                }
            }
        }
        foreach ($blueprint->columns as $column) {
            $definitions[] = $this->columnSql($column, inlinePrimary: $primary === []);
        }
        if ($primary !== []) {
            $definitions[] = ($namedPrimary ? 'CONSTRAINT ' . $q((string) $blueprint->primaryKeyName) . ' ' : '') . 'PRIMARY KEY (' . implode(', ', array_map($q, $primary)) . ')';
        }
        foreach ($blueprint->foreignKeys as $fk) {
            if ($fk->referencedTable === null) {
                continue;
            }
            $definitions[] = $this->foreignKeySql($fk);
        }
        foreach ($blueprint->checks as $check) {
            $definitions[] = $this->checkSql($blueprint->table, $check['expression'], $check['name'] ?? null);
        }
        $create = 'CREATE TABLE ' . ($ifNotExists ? 'IF NOT EXISTS ' : '') . $q($blueprint->table) . ' (' . implode(', ', $definitions) . ')';
        if ($driver === 'mysql') {
            $create .= ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4';
        }
        $statements[] = $create;
        foreach ($this->commentStatements($blueprint->table, $blueprint->columns) as $statement) {
            $statements[] = $statement;
        }
        foreach ($this->indexStatements($blueprint, $ifNotExists) as $statement) {
            $statements[] = $statement;
        }

        return $statements;
    }

    /** @return list<string> */
    public function compileAddColumns(Blueprint $blueprint): array
    {
        $q = fn (string $s) => $this->connection->quote($s);
        $this->assertSupported($blueprint->columns, $blueprint->primaryKeys);
        $statements = $this->enumTypeStatements($blueprint->columns);
        $uniqueIndexes = [];
        foreach ($blueprint->columns as $column) {
            // SQLite cannot ADD COLUMN ... UNIQUE: add the column, then a unique index
            $separateUnique = $column->unique && ! $column->primary && $this->connection->driver() === 'sqlite';
            if ($separateUnique) {
                $column->unique = false;
                $uniqueIndexes[] = $column->name;
            }
            $statements[] = 'ALTER TABLE ' . $q($blueprint->table) . ' ADD COLUMN ' . $this->columnSql($column, inlinePrimary: true, forAlter: true);
            if ($separateUnique) {
                $column->unique = true;
            }
            if ($this->connection->driver() === 'pgsql' && ! $column->nullable && ! $column->primary
                && ! ($column->hasDefault && $column->default !== null) && $this->implicitDefault($column) !== null) {
                // the DEFAULT only filled the existing rows: the column itself has none
                $statements[] = 'ALTER TABLE ' . $q($blueprint->table) . ' ALTER COLUMN ' . $q($column->name) . ' DROP DEFAULT';
            }
        }
        foreach ($uniqueIndexes as $name) {
            $statements[] = 'CREATE UNIQUE INDEX ' . $q(self::indexName($blueprint->table, [$name], true)) . ' ON ' . $q($blueprint->table) . ' (' . $q($name) . ')';
        }
        foreach ($this->commentStatements($blueprint->table, $blueprint->columns) as $statement) {
            $statements[] = $statement;
        }
        foreach ($blueprint->foreignKeys as $fk) {
            if ($fk->referencedTable === null || $this->connection->driver() === 'sqlite') {
                continue; // SQLite cannot ADD CONSTRAINT: Schema::alterFromBlueprint() rebuilds the table instead
            }
            $statements[] = $this->compileAddForeignKey($blueprint->table, $fk);
        }
        foreach ($this->indexStatements($blueprint, false) as $statement) {
            $statements[] = $statement;
        }

        return $statements;
    }

    public function compileAddForeignKey(string $table, ForeignKeyDefinition|ForeignKey $fk): string
    {
        return 'ALTER TABLE ' . $this->connection->quote($table) . ' ADD ' . $this->foreignKeySql($fk);
    }

    /** `[CONSTRAINT name] FOREIGN KEY (cols) REFERENCES table (cols) [ON DELETE …] [ON UPDATE …]` */
    public function foreignKeySql(ForeignKeyDefinition|ForeignKey $fk): string
    {
        $q = fn (string $s) => $this->connection->quote($s);
        if ($fk instanceof ForeignKeyDefinition) {
            [$columns, $table, $referenced, $onDelete, $onUpdate, $name] = [
                $fk->constrainedColumns(), (string) $fk->referencedTable, $fk->referencedColumnList(), $fk->onDeleteAction, $fk->onUpdateAction, $fk->constraintName,
            ];
        } else {
            [$columns, $table, $referenced, $onDelete, $onUpdate, $name] = [
                $fk->columns, $fk->referencedTable, $fk->referencedColumns, $fk->onDelete, $fk->onUpdate, $fk->explicitName ? $fk->name : null,
            ];
        }
        $sql = ($name !== null ? 'CONSTRAINT ' . $q($name) . ' ' : '')
            . 'FOREIGN KEY (' . implode(', ', array_map($q, $columns)) . ') REFERENCES ' . $q($table)
            . ' (' . implode(', ', array_map($q, $referenced)) . ')';
        $onDelete = ForeignKeyDefinition::action($onDelete);
        $onUpdate = ForeignKeyDefinition::action($onUpdate);
        if ($onDelete !== null) {
            $sql .= ' ON DELETE ' . $onDelete;
        }
        if ($onUpdate !== null) {
            $sql .= ' ON UPDATE ' . $onUpdate;
        }

        return $sql;
    }

    public function checkSql(string $table, string $expression, ?string $name = null): string
    {
        return 'CONSTRAINT ' . $this->connection->quote($name ?? Check::defaultName($table, $expression)) . ' CHECK (' . $expression . ')';
    }

    public function compileAddCheck(string $table, Check $check): string
    {
        return 'ALTER TABLE ' . $this->connection->quote($table) . ' ADD ' . $this->checkSql($table, $check->expression, $check->name);
    }

    public function compileDropCheck(string $table, string $name): string
    {
        $keyword = $this->connection->platform() === 'mysql' ? 'CHECK' : 'CONSTRAINT';

        return 'ALTER TABLE ' . $this->connection->quote($table) . " DROP $keyword " . $this->connection->quote($name);
    }

    public function compileDropForeign(string $table, string $name): string
    {
        $keyword = $this->connection->driver() === 'mysql' ? 'FOREIGN KEY' : 'CONSTRAINT';

        return 'ALTER TABLE ' . $this->connection->quote($table) . " DROP $keyword " . $this->connection->quote($name);
    }

    public function compileCreateIndex(string $table, Index $index, bool $ifNotExists = false): string
    {
        $q = fn (string $s) => $this->connection->quote($s);
        $supportsIfNotExists = $this->connection->driver() !== 'mysql' || $this->connection->platform() === 'mariadb';
        $driver = $this->connection->driver();
        $using = $index->using !== null && $index->using !== '' ? strtoupper($index->using) : null;
        $columns = implode(', ', array_map(function (string $column) use ($q, $index, $driver): string {
            $sql = $q($column);
            if (isset($index->lengths[$column]) && $driver === 'mysql') {
                $sql .= '(' . (int) $index->lengths[$column] . ')';
            }
            $sort = strtoupper((string) ($index->sorts[$column] ?? ''));

            return $sort === 'DESC' ? $sql . ' DESC' : ($sort === 'ASC' ? $sql . ' ASC' : $sql);
        }, $index->columns));
        $sql = 'CREATE ' . ($index->unique ? 'UNIQUE ' : '') . 'INDEX '
            . ($ifNotExists && $supportsIfNotExists ? 'IF NOT EXISTS ' : '')
            . $q($index->name ?? self::indexName($table, $index->columns, $index->unique)) . ' ON ' . $q($table)
            . ($using !== null && $driver === 'pgsql' ? ' USING ' . $using : '')
            . ' (' . $columns . ')'
            . ($using !== null && $driver === 'mysql' && in_array($using, ['HASH', 'BTREE'], true) ? ' USING ' . $using : '');
        if ($index->where !== null && $this->connection->driver() !== 'mysql') {
            $sql .= ' WHERE ' . $index->where;
        }

        return $sql;
    }

    public function compileDropIndex(string $table, Index $index): string
    {
        $q = fn (string $s) => $this->connection->quote($s);

        return match (true) {
            $this->connection->driver() === 'mysql' => 'ALTER TABLE ' . $q($table) . ' DROP INDEX ' . $q((string) $index->name),
            $this->connection->driver() === 'pgsql' && $index->constraint => 'ALTER TABLE ' . $q($table) . ' DROP CONSTRAINT ' . $q((string) $index->name),
            default => 'DROP INDEX ' . $q((string) $index->name),
        };
    }

    /** @param list<string> $columns @param ?string $name constraint name (PostgreSQL; other databases ignore it) */
    public function compileAddPrimary(string $table, array $columns, ?string $name = null): string
    {
        return 'ALTER TABLE ' . $this->connection->quote($table) . ' ADD '
            . ($name !== null && $this->connection->driver() === 'pgsql' ? 'CONSTRAINT ' . $this->connection->quote($name) . ' ' : '')
            . 'PRIMARY KEY (' . implode(', ', array_map(fn ($c) => $this->connection->quote($c), $columns)) . ')';
    }

    public function compileDropPrimary(string $table, ?string $constraintName): string
    {
        return $this->connection->driver() === 'mysql'
            ? 'ALTER TABLE ' . $this->connection->quote($table) . ' DROP PRIMARY KEY'
            : 'ALTER TABLE ' . $this->connection->quote($table) . ' DROP CONSTRAINT ' . $this->connection->quote((string) ($constraintName ?? $table . '_pkey'));
    }

    /**
     * Statements turning column $from into $to (MySQL/MariaDB: one MODIFY; PostgreSQL: one statement per
     * changed aspect — `$changes` says which: type, nullable, default, comment; all when omitted). SQLite has
     * no ALTER COLUMN: Schema rebuilds the table instead.
     *
     * @param array{type?: bool, nullable?: bool, default?: bool, comment?: bool}|null $changes
     * @return list<string>
     */
    public function compileChangeColumn(string $table, Column $to, ?Column $from = null, ?array $changes = null): array
    {
        $q = fn (string $s) => $this->connection->quote($s);
        $t = $q($table);
        $c = $q($to->name);
        $to = $this->resolve($to);
        if ($this->connection->driver() === 'mysql') {
            return ['ALTER TABLE ' . $t . ' MODIFY ' . $this->columnSql($to, inlinePrimary: false, forChange: true)];
        }
        $changes ??= ['type' => true, 'nullable' => true, 'default' => true, 'comment' => true];
        $statements = [];
        if ($changes['type'] ?? false) {
            array_push($statements, ...$this->enumTypeStatements([$to]));
            $type = match (strtoupper($this->typeSql($to))) {
                'SERIAL' => 'INTEGER',
                'BIGSERIAL' => 'BIGINT',
                'SMALLSERIAL' => 'SMALLINT',
                default => $this->typeSql($to),
            };
            // the old default may not cast to the new type: drop it first, set it again below
            if ($from === null || $from->hasDefault) {
                $statements[] = "ALTER TABLE $t ALTER COLUMN $c DROP DEFAULT";
                $changes['default'] = true;
            }
            $using = $to->enumName !== null || $from?->enumName !== null ? "$c::text::$type" : "$c::$type";
            $statements[] = "ALTER TABLE $t ALTER COLUMN $c TYPE $type"
                . ($to->collation !== null ? ' COLLATE ' . $q($to->collation) : '')
                . " USING $using";
        }
        if ($changes['nullable'] ?? false) {
            $statements[] = "ALTER TABLE $t ALTER COLUMN $c " . ($to->nullable ? 'DROP NOT NULL' : 'SET NOT NULL');
        }
        if (($changes['default'] ?? false) && ! $to->autoIncrement) {
            $statements[] = $to->hasDefault && $to->default !== null
                ? "ALTER TABLE $t ALTER COLUMN $c SET DEFAULT " . $this->defaultSql($to, $to->default)
                : "ALTER TABLE $t ALTER COLUMN $c DROP DEFAULT";
        }
        if ($changes['comment'] ?? false) {
            $statements[] = "COMMENT ON COLUMN $t.$c IS " . ($to->comment !== null && $to->comment !== '' ? $this->literal($to->comment) : 'NULL');
        }

        return array_values(array_unique($statements));
    }

    public function compileDropTable(string $table, bool $ifExists = false): string
    {
        $sql = 'DROP TABLE ' . ($ifExists ? 'IF EXISTS ' : '') . $this->connection->quote($table);

        return $this->connection->driver() === 'pgsql' ? $sql . ' CASCADE' : $sql;
    }

    public function compileDropColumn(string $table, string $column): string
    {
        return 'ALTER TABLE ' . $this->connection->quote($table) . ' DROP COLUMN ' . $this->connection->quote($column);
    }

    public function compileRenameColumn(string $table, string $from, string $to): string
    {
        return 'ALTER TABLE ' . $this->connection->quote($table) . ' RENAME COLUMN ' . $this->connection->quote($from) . ' TO ' . $this->connection->quote($to);
    }

    public function compileRenameTable(string $from, string $to): string
    {
        return $this->connection->driver() === 'mysql'
            ? 'RENAME TABLE ' . $this->connection->quote($from) . ' TO ' . $this->connection->quote($to)
            : 'ALTER TABLE ' . $this->connection->quote($from) . ' RENAME TO ' . $this->connection->quote($to);
    }

    public function compileHasTable(string $table): array
    {
        return match ($this->connection->driver()) {
            'sqlite' => ["SELECT name FROM sqlite_master WHERE type = 'table' AND name = :t", ['t' => $table]],
            'mysql' => ['SELECT table_name FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = :t', ['t' => $table]],
            default => ["SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = :t", ['t' => $table]],
        };
    }

    public function columnSql(Column $column, bool $inlinePrimary, bool $forAlter = false, bool $forChange = false): string
    {
        $driver = $this->connection->driver();
        $column = $this->resolve($column);
        $type = $this->typeSql($column);
        $sql = $this->connection->quote($column->name) . ($type !== '' ? ' ' . $type : '') . $this->collationSql($column);
        if ($column->identity !== null && $column->autoIncrement && $driver === 'pgsql') {
            $sql .= ' GENERATED ' . ($column->identity === 'ALWAYS' ? 'ALWAYS' : 'BY DEFAULT') . ' AS IDENTITY';
        }
        if ($column->autoIncrement && $column->primary && $inlinePrimary) {
            return $sql . match ($driver) {
                'sqlite' => ' PRIMARY KEY AUTOINCREMENT',
                'mysql' => ' AUTO_INCREMENT PRIMARY KEY',
                default => ' PRIMARY KEY',
            } . $this->mysqlCommentSql($column);
        }
        if ($column->generatedType !== null && $column->asExpression !== null) {
            // computed by the database: no NOT NULL / DEFAULT (MariaDB refuses them)
            return $sql . ' GENERATED ALWAYS AS (' . $column->asExpression . ') ' . $this->generatedKeyword($column)
                . ($column->primary && $inlinePrimary ? ' PRIMARY KEY' : '') . $this->mysqlCommentSql($column);
        }
        if ($column->primary && $inlinePrimary) {
            $sql .= ' PRIMARY KEY';
        } elseif (! $column->nullable || $column->primary) {
            $sql .= ' NOT NULL';
        } elseif ($forChange) {
            $sql .= ' NULL';
        }
        if ($column->autoIncrement && $driver === 'mysql' && ! $inlinePrimary) {
            $sql .= ' AUTO_INCREMENT';
        }
        if ($column->hasDefault && $column->default !== null) {
            $sql .= ' DEFAULT ' . $this->defaultSql($column, $column->default);
        } elseif ($forAlter && ! $column->nullable && ! $column->primary && $driver === 'sqlite') {
            $sql .= ' DEFAULT ' . ($this->implicitDefault($column) ?? "''");
        } elseif ($forAlter && ! $column->nullable && ! $column->primary && $driver === 'pgsql' && ($implicit = $this->implicitDefault($column)) !== null) {
            // PostgreSQL rejects ADD COLUMN ... NOT NULL on a non-empty table unless there is a default;
            // Schema drops this temporary default right after (MySQL/MariaDB fill the type default themselves).
            $sql .= ' DEFAULT ' . $implicit;
        }
        if ($column->unique && ! $column->primary && ! $forChange) {
            $sql .= ' UNIQUE';
        }
        if ($driver === 'sqlite' && in_array($column->type, ['enum', 'simple-enum'], true) && $column->values !== []) {
            $sql .= ' CHECK (' . $this->enumCheck($column) . ')';
        }

        return $sql . $this->mysqlCommentSql($column);
    }

    /** The CHECK expression SQLite enum columns get: "col" IN ('a', 'b'). */
    public function enumCheck(Column $column): string
    {
        return $this->connection->quote($column->name) . ' IN (' . implode(', ', array_map(fn ($v) => $this->literal((string) $v), $column->values)) . ')';
    }

    /**
     * The column as this platform writes it: a generated uuid gets DEFAULT gen_random_uuid() on PostgreSQL
     * (13+; the ORM generates uuids itself on the other databases).
     */
    public function resolve(Column $column): Column
    {
        if ($column->generated === 'uuid' && ! ($column->hasDefault && $column->default !== null) && $this->connection->driver() === 'pgsql') {
            $column = clone $column;
            $column->default = new SqlExpression('gen_random_uuid()');
            $column->hasDefault = true;
        }

        return $column;
    }

    private function generatedKeyword(Column $column): string
    {
        $virtual = strtoupper((string) $column->generatedType) === 'VIRTUAL';
        if ($virtual && $this->connection->driver() === 'pgsql' && (int) $this->connection->serverVersion() < 18) {
            throw new OrmException("Generated column \"{$column->name}\": PostgreSQL before 18 only has STORED generated columns (generatedType: 'STORED').");
        }

        return $virtual ? 'VIRTUAL' : 'STORED';
    }

    /**
     * Features only some databases have.
     *
     * @param list<Column> $columns
     * @param list<string> $primaryKeys
     */
    private function assertSupported(array $columns, array $primaryKeys): void
    {
        $driver = $this->connection->driver();
        foreach ($columns as $column) {
            if ($column->array && $driver !== 'pgsql') {
                throw new OrmException("Column \"{$column->name}\": array columns (array: true) need PostgreSQL; use simple-array or json on {$this->connection->platform()}.");
            }
            if ($column->autoIncrement && ! $column->primary && ! in_array($column->name, $primaryKeys, true) && $column->generated !== null && $driver !== 'pgsql') {
                throw new OrmException("Column \"{$column->name}\": #[Generated('increment')] on a column that is not the primary key needs PostgreSQL.");
            }
        }
    }

    /** DEFAULT clause value; MySQL only accepts expression defaults ("(...)") on TEXT/JSON/BLOB columns. */
    public function defaultSql(Column $column, mixed $value): string
    {
        if ($value instanceof SqlExpression) {
            return $value->sql;
        }
        if (in_array($column->type, ['enum', 'simple-enum'], true) && (is_int($value) || is_float($value) || $value instanceof \BackedEnum)) {
            $value = (string) ($value instanceof \BackedEnum ? $value->value : $value); // a label, not a position
        }
        $literal = $this->literal($value);
        if ($value !== null && $this->connection->driver() === 'mysql' && $this->connection->platform() === 'mysql'
            && in_array($column->type, ['text', 'mediumtext', 'longtext', 'json', 'jsonb', 'simple-json', 'simple-array', 'blob', 'binary'], true)
            && $literal !== 'CURRENT_TIMESTAMP') {
            return '(' . $literal . ')';
        }

        return $literal;
    }

    /** Neutral value used to fill existing rows when a NOT NULL column without default is added. */
    public function implicitDefault(Column $column): ?string
    {
        if (($custom = TypeRegistry::get($column->type)) !== null) {
            return $custom->implicitDefault($this->connection->platform());
        }
        if ($column->array) {
            return "'{}'";
        }

        return match ($column->type) {
            'int', 'integer', 'smallint', 'tinyint', 'mediumint', 'bigint', 'float', 'double', 'real', 'decimal', 'numeric' => '0',
            'bool', 'boolean' => $this->connection->driver() === 'pgsql' ? 'FALSE' : '0',
            'string', 'varchar', 'char', 'text', 'mediumtext', 'longtext', 'enum' => "''",
            'json', 'jsonb', 'simple-json' => "'{}'",
            'simple-array' => "''",
            default => null, // dates / uuid have no neutral value: the table must be empty
        };
    }

    public function typeSql(Column $column): string
    {
        if ($column->sqlType !== null && $column->sqlType !== '') {
            return $column->sqlType . ($column->array && $this->connection->driver() === 'pgsql' ? '[]' : '');
        }
        if ($column->rawType !== null && $this->connection->driver() === 'sqlite') {
            return $column->rawType; // introspected SQLite declaration, kept verbatim by table rebuilds
        }
        if (($custom = TypeRegistry::get($column->type)) !== null) {
            return $custom->sqlDeclaration($column, $this->connection->platform()) . ($column->array ? '[]' : '');
        }
        $sql = $this->baseTypeSql($column);
        if ($column->unsigned && $this->connection->driver() === 'mysql'
            && in_array($column->type, ['int', 'integer', 'smallint', 'tinyint', 'mediumint', 'bigint', 'float', 'double', 'real', 'decimal', 'numeric'], true)) {
            $sql .= ' UNSIGNED';
        }

        return $column->array && $this->connection->driver() === 'pgsql' ? $sql . '[]' : $sql;
    }

    private function baseTypeSql(Column $column): string
    {
        $driver = $this->connection->driver();
        // SERIAL types: auto-increment keys and #[Generated('increment')] columns, not identity columns or arrays
        $auto = $column->autoIncrement && $column->identity === null && ! $column->array
            && ($column->primary || $column->generated === 'increment' || $column->generated === 'identity');
        $fraction = $column->precision !== null ? '(' . $column->precision . ')' : '';

        return match (strtolower($column->type)) {
            'int', 'integer', 'int4' => $driver === 'pgsql' ? ($auto ? 'SERIAL' : 'INTEGER') : 'INTEGER',
            'smallint', 'int2' => match ($driver) {
                'pgsql' => $auto ? 'SMALLSERIAL' : 'SMALLINT',
                'sqlite' => 'INTEGER',
                default => 'SMALLINT',
            },
            'tinyint' => match ($driver) {
                'mysql' => 'TINYINT',
                'pgsql' => 'SMALLINT',
                default => 'INTEGER',
            },
            'mediumint' => $driver === 'mysql' ? 'MEDIUMINT' : 'INTEGER',
            'bigint', 'int8' => match ($driver) {
                'pgsql' => $auto ? 'BIGSERIAL' : 'BIGINT',
                'sqlite' => 'INTEGER',
                default => 'BIGINT',
            },
            'float', 'double', 'double precision', 'float8' => match ($driver) {
                'sqlite' => 'REAL',
                'mysql' => 'DOUBLE',
                default => 'DOUBLE PRECISION',
            },
            'real', 'float4' => match ($driver) {
                'mysql' => 'DOUBLE',
                default => 'REAL',
            },
            'decimal', 'numeric' => sprintf('DECIMAL(%d, %d)', $column->precision ?? 10, $column->scale ?? 2),
            'bool', 'boolean' => match ($driver) {
                'mysql' => 'TINYINT(1)',
                'sqlite' => 'INTEGER',
                default => 'BOOLEAN',
            },
            'string', 'varchar', 'character varying', 'nvarchar' => 'VARCHAR(' . ($column->length ?? 255) . ')',
            'char', 'character', 'nchar' => 'CHAR(' . ($column->length ?? 1) . ')',
            'text' => 'TEXT',
            'tinytext', 'mediumtext', 'longtext' => $driver === 'mysql' ? strtoupper($column->type) : 'TEXT',
            'datetime', 'timestamp' => match ($driver) {
                'pgsql' => 'TIMESTAMP' . $fraction,
                'mysql' => 'DATETIME' . $fraction,
                default => 'DATETIME',
            },
            'timestamptz', 'timestamp with time zone' => match ($driver) {
                'pgsql' => 'TIMESTAMPTZ' . $fraction,
                'mysql' => 'TIMESTAMP' . $fraction,
                default => 'DATETIME',
            },
            'date' => 'DATE',
            'time' => $driver === 'sqlite' ? 'TIME' : 'TIME' . $fraction,
            'json', 'jsonb' => match ($driver) {
                'mysql' => 'JSON',
                'pgsql' => 'JSONB',
                default => 'TEXT',
            },
            'simple-json', 'simple-array' => 'TEXT',
            'uuid' => $driver === 'pgsql' ? 'UUID' : 'CHAR(36)',
            'enum', 'simple-enum' => match (true) {
                $driver === 'mysql' && $column->values !== [] => 'ENUM(' . implode(', ', array_map(fn ($v) => $this->literal((string) $v), $column->values)) . ')',
                $driver === 'pgsql' && $column->enumName !== null => $this->connection->quote($column->enumName),
                default => 'VARCHAR(' . ($column->length ?? 255) . ')',
            },
            'blob', 'bytea', 'longblob', 'mediumblob', 'tinyblob' => match ($driver) {
                'pgsql' => 'BYTEA',
                'mysql' => in_array($column->type, ['longblob', 'mediumblob', 'tinyblob'], true) ? strtoupper($column->type) : 'BLOB',
                default => 'BLOB',
            },
            'binary', 'varbinary' => match ($driver) {
                'pgsql' => 'BYTEA',
                'mysql' => $column->length !== null ? strtoupper($column->type) . '(' . $column->length . ')' : 'BLOB',
                default => 'BLOB',
            },
            default => strtoupper($column->type) . ($column->length !== null ? '(' . $column->length . ')' : ''),
        };
    }

    private function collationSql(Column $column): string
    {
        $sql = '';
        $driver = $this->connection->driver();
        if ($column->charset !== null && $driver === 'mysql') {
            $sql .= ' CHARACTER SET ' . $column->charset;
        }
        if ($column->collation !== null) {
            $sql .= ' COLLATE ' . ($driver === 'pgsql' ? $this->connection->quote($column->collation) : $column->collation);
        }

        return $sql;
    }

    private function mysqlCommentSql(Column $column): string
    {
        return $column->comment !== null && $column->comment !== '' && $this->connection->driver() === 'mysql'
            ? ' COMMENT ' . $this->literal($column->comment)
            : '';
    }

    /** PostgreSQL column comments are separate statements. @param list<Column> $columns @return list<string> */
    private function commentStatements(string $table, array $columns): array
    {
        if ($this->connection->driver() !== 'pgsql') {
            return [];
        }
        $statements = [];
        foreach ($columns as $column) {
            if ($column->comment !== null && $column->comment !== '') {
                $statements[] = 'COMMENT ON COLUMN ' . $this->connection->quote($table) . '.' . $this->connection->quote($column->name) . ' IS ' . $this->literal($column->comment);
            }
        }

        return $statements;
    }

    /**
     * CREATE TYPE for PostgreSQL native enums (columns with enumName), skipped when the type exists.
     *
     * @param list<Column> $columns
     * @return list<string>
     */
    public function enumTypeStatements(array $columns): array
    {
        if ($this->connection->driver() !== 'pgsql') {
            return [];
        }
        $statements = [];
        foreach ($columns as $column) {
            if ($column->enumName !== null && in_array($column->type, ['enum', 'simple-enum'], true)) {
                $statements[] = 'DO $$ BEGIN CREATE TYPE ' . $this->connection->quote($column->enumName) . ' AS ENUM ('
                    . implode(', ', array_map(fn ($v) => $this->literal((string) $v), $column->values))
                    . '); EXCEPTION WHEN duplicate_object THEN NULL; END $$';
            }
        }

        return $statements;
    }

    /** @return list<string> */
    private function indexStatements(Blueprint $blueprint, bool $ifNotExists): array
    {
        $statements = [];
        $indexes = $blueprint->indexes;
        foreach ($blueprint->columns as $column) {
            if ($column->index) {
                $indexes[] = ['columns' => [$column->name], 'unique' => false, 'name' => null];
            }
        }
        foreach ($indexes as $index) {
            $statements[] = $this->compileCreateIndex($blueprint->table, new Index(
                $index['columns'],
                $index['unique'],
                $index['name'] ?? self::indexName($blueprint->table, $index['columns'], $index['unique']),
                where: $index['where'] ?? null,
                sorts: $index['sorts'] ?? [],
                lengths: $index['lengths'] ?? [],
                using: $index['using'] ?? null,
            ), $ifNotExists);
        }

        return $statements;
    }

    /** @see Index::defaultName() @param list<string> $columns */
    public static function indexName(string $table, array $columns, bool $unique): string
    {
        return Index::defaultName($table, $columns, $unique);
    }

    /** DDL cannot use bound parameters: quote defaults through PDO. */
    public function literal(mixed $value): string
    {
        if ($value === null) {
            return 'NULL';
        }
        if ($value instanceof SqlExpression) {
            return $value->sql;
        }
        if ($value instanceof \BackedEnum) {
            $value = $value->value;
        }
        if (is_bool($value)) {
            return $this->connection->driver() === 'pgsql' ? ($value ? 'TRUE' : 'FALSE') : ($value ? '1' : '0');
        }
        if (is_int($value) || is_float($value)) {
            return (string) $value;
        }
        if ($value instanceof \DateTimeInterface) {
            $value = $value->format('Y-m-d H:i:s');
        }
        if (is_array($value)) {
            $value = json_encode($value, JSON_THROW_ON_ERROR);
        }
        if (is_string($value) && strtoupper($value) === 'CURRENT_TIMESTAMP') {
            return 'CURRENT_TIMESTAMP';
        }

        return $this->connection->pdo()->quote((string) $value);
    }
